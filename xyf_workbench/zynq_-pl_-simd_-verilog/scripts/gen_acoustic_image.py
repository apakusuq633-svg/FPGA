#!/usr/bin/env python3
"""Package the real RV32 acoustic image and independent golden results for PS.

默认验收镜像要求 PUSH/VRED/VFFT，禁止 VUPD。
ACOUSTIC_BASELINE=1 要求所有自定义指令静态及动态均为零。
ACOUSTIC_LIVE=1 打包真实定位固件；FIR 由自主音频控制器执行，不在固件中发 PUSH/VRED。
ACOUSTIC_IMAGE_OUT 指定输出头文件路径。
"""
from pathlib import Path
import hashlib
import os
import re

ROOT = Path(__file__).resolve().parents[1]

LIVE = os.environ.get("ACOUSTIC_LIVE") == "1"
BASELINE = os.environ.get("ACOUSTIC_BASELINE") == "1"
OUT_PATH = ROOT / os.environ.get("ACOUSTIC_IMAGE_OUT", "sw/acoustic_image.h")


def words(path, count=None):
    lines = (ROOT / path).read_text(encoding="ascii").splitlines()
    if not lines or any(not re.fullmatch(r"[0-9a-fA-F]{1,8}", s) for s in lines):
        raise RuntimeError("invalid or empty hex: " + path)
    result = [int(s, 16) for s in lines]
    if count is not None and len(result) != count:
        raise RuntimeError(f"{path}: expected {count} words, got {len(result)}")
    return result


def main():
    stem = "fw_live" if LIVE else "fw"
    itcm = words(f"sw/fw/{stem}_itcm.hex")
    dtcm = words(f"sw/fw/{stem}_dtcm.hex")
    if len(itcm) > 4096 or len(dtcm) * 4 > 0x2800:
        raise RuntimeError("acoustic image exceeds TCM/input region")
    counts = {f: sum((w & 127) == 11 and ((w >> 12) & 7) == f for w in itcm)
              for f in (0, 1, 2, 7)}
    if LIVE:
        if counts[2] or not counts[7]:
            raise RuntimeError("live image requires VFFT and forbids VUPD")
    elif BASELINE:
        # Baseline must not contain any accelerator instructions.
        if any(counts.values()):
            raise RuntimeError(
                "baseline image must contain no custom instruction, got " + repr(counts))
    elif not all(counts[f] for f in (0, 1, 7)) or counts[2]:
        raise RuntimeError("PUSH/VRED/VFFT required and VUPD forbidden in DAS/FIR image")
    das = words("build/fw_das_fp.hex", 6)
    fir = words("build/fw_fir_fp.hex", 2)
    # Address/value pairs; independent FIR fingerprints reject bypassed filtering.
    checks = [(0x2800, 8519680), (0x2808, 260), (0x2810, 89440),
              (0x2838, 16), (0x2834, 7), (0x283C, 0xC0DE0001)]
    checks += [(0x2800 + 4 * (22 + i), value) for i, value in enumerate(das)]
    checks += [(0x38C0 + 4 * i, value) for i, value in enumerate(fir + fir)]
    fft = words("build/fw_fft_ref.hex", 1026)
    arrays = {
        "acoustic_itcm": itcm, "acoustic_dtcm": dtcm,
        "acoustic_fir_coeff": words("build/fw_fir_coeff.hex", 32),
        "acoustic_steer_lut": words("build/steer_lut.hex", 2048),
        "acoustic_fft_ref": [(fft[i] & 65535) | ((fft[i+1] & 65535) << 16)
                             for i in range(0, len(fft), 2)],
        "acoustic_gcc_ref": words("build/fw_gcc_ref.hex", 1024),
        "acoustic_check_addr": [a for a, _ in checks],
        "acoustic_check_value": [v for _, v in checks],
    }
    guard = "ACOUSTIC_LIVE_IMAGE_H" if LIVE else ("ACOUSTIC_IMAGE_BASE_H" if BASELINE else "ACOUSTIC_IMAGE_H")
    out = [f"/* Generated by scripts/gen_acoustic_image.py; do not edit."
           f"{'  [BASELINE: FW_ACCEL=0]' if BASELINE else ''} */",
           f"#ifndef {guard}", f"#define {guard}", "#include <stdint.h>"]
    for name, values in arrays.items():
        out.append(f"#define {name.upper()}_WORDS {len(values)}u")
        out.append(f"static const uint32_t {name}[] = {{")
        for i in range(0, len(values), 8):
            out.append("    " + ", ".join(f"0x{v:08x}u" for v in values[i:i+8]) + ",")
        out.append("};")
    digest = hashlib.sha256((ROOT / f"sw/fw/{stem}_itcm.hex").read_bytes()).hexdigest()
    data_digest = hashlib.sha256((ROOT / f"sw/fw/{stem}_dtcm.hex").read_bytes()).hexdigest()
    out += [f'#define ACOUSTIC_ITCM_SHA256 "{digest}"',
            f'#define ACOUSTIC_DTCM_SHA256 "{data_digest}"', "#endif", ""]
    OUT_PATH.write_text("\n".join(out), encoding="ascii")
    print(f"ACOUSTIC_IMAGE_PASS: {OUT_PATH.name} ITCM={len(itcm)} DTCM={len(dtcm)} "
          f"instructions={counts}{'  [BASELINE]' if BASELINE else ''}")


if __name__ == "__main__":
    main()
