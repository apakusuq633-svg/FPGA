module rv_id_ex_reg (
  input         clk_i,
  input         rst_n_i,
  input         hold_i,
  input         flush_i,
  input         valid_i,
  input  [31:0] pc_i,
  input  [31:0] instr_i,
  input  [31:0] rs1_value_i,
  input  [31:0] rs2_value_i,
  input  [31:0] imm_i,
  input  [4:0]  rs1_i,
  input  [4:0]  rs2_i,
  input  [4:0]  rd_i,
  input  [4:0]  alu_op_i,
  input  [2:0]  branch_op_i,
  input  [1:0]  wb_sel_i,
  input  [1:0]  mem_size_i,
  input         op_a_pc_i,
  input         op_a_zero_i,
  input         op_b_imm_i,
  input         reg_write_i,
  input         mem_read_i,
  input         mem_write_i,
  input         load_unsigned_i,
  input         branch_i,
  input         jal_i,
  input         jalr_i,
  input         is_call_i,
  input         is_return_i,
  input         mret_i,
  input         csr_valid_i,
  input  [11:0] csr_addr_i,
  input  [1:0]  csr_op_i,
  input         csr_imm_i,
  input         csr_write_i,
  input         pred_taken_i,
  input  [31:0] pred_target_i,
  input  [5:0]  pht_index_i,
  input  [3:0]  fault_i,
  output        valid_o,
  output [31:0] pc_o,
  output [31:0] instr_o,
  output [31:0] rs1_value_o,
  output [31:0] rs2_value_o,
  output [31:0] imm_o,
  output [4:0]  rs1_o,
  output [4:0]  rs2_o,
  output [4:0]  rd_o,
  output [4:0]  alu_op_o,
  output [2:0]  branch_op_o,
  output [1:0]  wb_sel_o,
  output [1:0]  mem_size_o,
  output        op_a_pc_o,
  output        op_a_zero_o,
  output        op_b_imm_o,
  output        reg_write_o,
  output        mem_read_o,
  output        mem_write_o,
  output        load_unsigned_o,
  output        branch_o,
  output        jal_o,
  output        jalr_o,
  output        is_call_o,
  output        is_return_o,
  output        mret_o,
  output        csr_valid_o,
  output [11:0] csr_addr_o,
  output [1:0]  csr_op_o,
  output        csr_imm_o,
  output        csr_write_o,
  output        pred_taken_o,
  output [31:0] pred_target_o,
  output [5:0]  pht_index_o,
  output [3:0]  fault_o
);

  // alu_op 加宽到 5 位（M 扩展要 18 个编码），其余字段未动。
  localparam WIDTH = 260;
  wire [WIDTH-1:0] payload_in;
  wire [WIDTH-1:0] payload_out;

  assign payload_in = {
    pc_i, instr_i, rs1_value_i, rs2_value_i, imm_i, rs1_i, rs2_i, rd_i,
    alu_op_i, branch_op_i, wb_sel_i, mem_size_i, op_a_pc_i, op_a_zero_i,
    op_b_imm_i, reg_write_i, mem_read_i, mem_write_i, load_unsigned_i,
    branch_i, jal_i, jalr_i, is_call_i, is_return_i, mret_i,
    csr_valid_i, csr_addr_i, csr_op_i, csr_imm_i, csr_write_i,
    pred_taken_i, pred_target_i, pht_index_i, fault_i
  };
  assign {
    pc_o, instr_o, rs1_value_o, rs2_value_o, imm_o, rs1_o, rs2_o, rd_o,
    alu_op_o, branch_op_o, wb_sel_o, mem_size_o, op_a_pc_o, op_a_zero_o,
    op_b_imm_o, reg_write_o, mem_read_o, mem_write_o, load_unsigned_o,
    branch_o, jal_o, jalr_o, is_call_o, is_return_o, mret_o,
    csr_valid_o, csr_addr_o, csr_op_o, csr_imm_o, csr_write_o,
    pred_taken_o, pred_target_o, pht_index_o, fault_o
  } = payload_out;

  rv_pipeline_reg #(.WIDTH(WIDTH)) u_pipeline_reg (
    .clk_i     (clk_i),
    .rst_n_i   (rst_n_i),
    .hold_i    (hold_i),
    .flush_i   (flush_i),
    .valid_i   (valid_i),
    .payload_i (payload_in),
    .valid_o   (valid_o),
    .payload_o (payload_out)
  );

endmodule
